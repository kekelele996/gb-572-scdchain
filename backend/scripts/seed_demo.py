"""Idempotent demo seed for the 嘉禾保险 customer-dimension yearbook.

Scene (see batch-plan gb-572):
  3 source systems · 180 customer business keys · 5 daily snapshots (900 rows)
  30 level changes -> 210 SCD2 chains · 24 cross-source conflict windows
  2 build runs (seed:v1 / seed:v2 幂等重跑) · 3 role accounts.

Determinism: every row is generated by ``src.services.fixture`` from SHA-256
derived seeds. Re-running upserts by natural keys (email / source code /
attribute key / source+key+date / run label) and never rewrites user edits or
resolutions. The script ends with the machine readable line

    SEED_SUMMARY brand=scdchain sources=3 customers=180 snapshots=900 conflicts=24 runs=2 users=3

which the batch QA compares literally across two runs.
"""
from __future__ import annotations

import sys
from pathlib import Path

if __package__ in (None, ""):  # `python scripts/seed_demo.py`
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import func, select  # noqa: E402

from src.config.database import SessionLocal, init_db  # noqa: E402
from src.constants.build_status import BuildStatus  # noqa: E402
from src.models.build_run import BuildRun  # noqa: E402
from src.models.conflict_item import ConflictItem  # noqa: E402
from src.models.customer_snapshot import CustomerSnapshot  # noqa: E402
from src.models.dim_customer import DimCustomer  # noqa: E402
from src.models.merge_rule import MergeRule  # noqa: E402
from src.models.source_system import SourceSystem  # noqa: E402
from src.models.user import User  # noqa: E402
from src.services import auth_service, build_service  # noqa: E402
from src.services.fixture import RULE_SPECS, build_dataset  # noqa: E402
from src.utils.hashing import stable_hash  # noqa: E402
from src.utils.logger import log_event  # noqa: E402

DEMO_PASSWORD = "Demo@2026"
ACCOUNTS = (
    ("admin@scdchain.io", "顾砚舟", "admin", "建模负责人：维度定义、合并规则、发布"),
    ("modeler@scdchain.io", "沈知微", "modeler", "建模工程师：跑构建、处理冲突、校验"),
    ("auditor@scdchain.io", "周予安", "auditor", "审计只读：任意时点回溯与导出"),
)
SEED_RUNS = (
    ("seed:v1", "seed：2026-11-01 ~ 11-05 基线构建"),
    ("seed:v2", "seed：同一批快照幂等重跑（验证确定性）"),
)
SUMMARY_KEYS = ("sources", "customers", "snapshots", "conflicts", "runs", "users")


def _get_or_create(db, model, predicate, values):
    row = db.execute(select(model).where(predicate)).scalar_one_or_none()
    if row is not None:
        return row, False
    row = model(**values)
    db.add(row)
    db.flush()
    return row, True


def _seed_sources(db) -> dict[str, SourceSystem]:
    dataset = build_dataset()
    sources: dict[str, SourceSystem] = {}
    for spec in dataset["sources"]:
        row, _ = _get_or_create(
            db,
            SourceSystem,
            SourceSystem.code == spec["code"],
            {
                "code": spec["code"],
                "name": spec["name"],
                "system_type": spec["system_type"],
                "description": spec["description"],
                "contact_owner": spec["contact_owner"],
                "snapshot_time": spec["snapshot_time"],
                "trust_level": spec["trust_level"],
            },
        )
        sources[row.code] = row
    db.commit()
    return sources


def _seed_users(db) -> None:
    for email, display_name, role, _note in ACCOUNTS:
        _get_or_create(
            db,
            User,
            User.email == email,
            {
                "email": email,
                "display_name": display_name,
                "role": role,
                "password_hash": auth_service.hash_password(DEMO_PASSWORD),
            },
        )
    db.commit()


def _seed_rules(db) -> None:
    for spec in RULE_SPECS:
        _get_or_create(
            db,
            MergeRule,
            MergeRule.attribute_key == spec["attribute_key"],
            {
                "attribute_key": spec["attribute_key"],
                "display_name": spec["display_name"],
                "data_type": spec["data_type"],
                "source_priority": spec["source_priority"],
                "normalization": spec["normalization"],
                "exclude_from_change": spec["exclude_from_change"],
                "description": f"{spec['display_name']} 的跨源合并策略（seed 基线，可在维度设计页调整）",
            },
        )
    db.commit()


def _seed_snapshots(db, sources: dict[str, SourceSystem]) -> int:
    dataset = build_dataset()
    inserted = 0
    for row in dataset["snapshots"]:
        source = sources.get(row["source_code"])
        if source is None:
            continue
        exists = db.execute(
            select(CustomerSnapshot.id).where(
                CustomerSnapshot.source_id == source.id,
                CustomerSnapshot.business_key == row["business_key"],
                CustomerSnapshot.snapshot_date == row["snapshot_date"],
            )
        ).scalar_one_or_none()
        if exists is not None:
            continue
        db.add(
            CustomerSnapshot(
                source_id=source.id,
                source_code=row["source_code"],
                business_key=row["business_key"],
                snapshot_date=row["snapshot_date"],
                attributes=row["attributes"],
                row_hash=stable_hash(row["attributes"]),
                ingested_at=row["ingested_at"],
                is_late=row["is_late"],
                batch_tag=row["batch_tag"],
            )
        )
        inserted += 1
    db.commit()
    return inserted


def _seed_builds(db) -> None:
    # A crashed previous seed may leave a pending run behind: retire it first.
    stale = (
        db.execute(
            select(BuildRun).where(BuildRun.status.in_([BuildStatus.PENDING.value, BuildStatus.RUNNING.value]))
        )
        .scalars()
        .all()
    )
    for run in stale:
        run.status = BuildStatus.FAILED.value
        run.error_message = "retired by seed re-run: interrupted build"
    db.commit()

    for label, notes in SEED_RUNS:
        exists = db.execute(select(BuildRun).where(BuildRun.label == label)).scalar_one_or_none()
        if exists is not None and exists.status == BuildStatus.SUCCEEDED.value:
            continue
        run = build_service.create_run(
            db,
            actor_email="seed@scdchain.io",
            label=label,
            notes=notes,
            dispatch=False,
        )
        outcome = build_service.execute_run(db, run.id)
        if not outcome.get("ok"):
            raise RuntimeError(f"seed build {label} failed: {outcome.get('error')}")
        log_event("SEED_BUILD_DONE", label=label, run_id=run.id, stats=outcome.get("stats"))


def _summary(db) -> dict:
    latest = build_service.latest_run(db)
    customers = 0
    if latest is not None:
        customers = int(
            db.execute(
                select(func.count(func.distinct(DimCustomer.business_key))).where(
                    DimCustomer.build_run_id == latest.id
                )
            ).scalar()
            or 0
        )
    return {
        "sources": int(db.execute(select(func.count(SourceSystem.id))).scalar() or 0),
        "customers": customers,
        "snapshots": int(db.execute(select(func.count(CustomerSnapshot.id))).scalar() or 0),
        "conflicts": int(db.execute(select(func.count(ConflictItem.id))).scalar() or 0),
        "runs": int(db.execute(select(func.count(BuildRun.id))).scalar() or 0),
        "users": int(db.execute(select(func.count(User.id))).scalar() or 0),
    }


def run_seed() -> dict:
    init_db()
    db = SessionLocal()
    try:
        sources = _seed_sources(db)
        _seed_users(db)
        _seed_rules(db)
        inserted = _seed_snapshots(db, sources)
        _seed_builds(db)
        summary = _summary(db)
        line = "SEED_SUMMARY brand=scdchain " + " ".join(f"{key}={summary[key]}" for key in SUMMARY_KEYS)
        print(line, flush=True)
        log_event("SEED_SUMMARY", **summary, inserted_snapshots=inserted)
        return summary
    finally:
        db.close()


if __name__ == "__main__":
    run_seed()
